# This script runs the 'site_tool' of a checkout of the gh-pages branch
# (or of the site generated by make_site_docker.sh) in the same Docker image
# make_site_docker.sh uses. This avoids having to install a Ruby version
# compatible with the site's Gemfile.lock on the host.
#
# Usage: site_tool_docker.sh <site dir> <site_tool arguments>
#
# Examples:
#   site_tool_docker.sh build/docker-site jekyll serve
#   site_tool_docker.sh ../kudu-site proof
#   site_tool_docker.sh ../kudu-site publish
#
# The site is served at http://localhost:4000/ by 'jekyll serve'; set
# SITE_PORT to use a different port.
#
# Environment variables:
#   SITE_PORT        The port on the host to serve the site at (default: 4000).
#   DOCKER_PLATFORM  The platform of the container, e.g. linux/amd64
#                    (default: the platform of the Docker host).
########################################################################
set -e
set -o pipefail

SOURCE_ROOT=$(cd $(dirname $0)/../../..; pwd)
IMAGE=kudu-site-builder
# The newest bundler version that supports the Ruby version in the image.
BUNDLER_VERSION=2.4.22

usage() {
  echo "Usage: $0 <site dir> <site_tool arguments>"
  echo "Example: $0 build/docker-site jekyll serve"
  exit 1
}

if [ $# -lt 2 ]; then
  usage
fi
if [ ! -x "$1/site_tool" ]; then
  echo "Error: $1 doesn't appear to be the root of the Kudu site:" \
    "site_tool not found"
  usage
fi
SITE_DIR=$(cd "$1"; pwd)
shift

# 'site_tool publish' verifies that the site matches the upstream gh-pages
# branch, so it must be run in a git checkout, not in a generated site.
if [ "$1" == "publish" ] && [ ! -e "$SITE_DIR/.git" ]; then
  echo "Error: $SITE_DIR is not a git checkout of the gh-pages branch."
  echo "Copy the generated documentation into a gh-pages checkout, commit and"
  echo "push it, then run '$0 <gh-pages checkout> publish'."
  exit 1
fi

if ! which docker >/dev/null 2>&1; then
  echo "Error: docker not found."
  exit 1
fi

if [ -n "$DOCKER_PLATFORM" ]; then
  PLATFORM_FLAG="--platform $DOCKER_PLATFORM"
  ARCH=${DOCKER_PLATFORM##*/}
else
  PLATFORM_FLAG=""
  ARCH=$(docker version --format '{{.Server.Arch}}')
fi

docker build -q $PLATFORM_FLAG -t "$IMAGE" \
  -f "$SOURCE_ROOT/docs/support/docker/Dockerfile" \
  "$SOURCE_ROOT/docker" > /dev/null

DOCKER_ARGS=(--rm --init $PLATFORM_FLAG)
if [ -t 0 ] && [ -t 1 ]; then
  DOCKER_ARGS+=(-it)
fi

# The site directory is mounted at the same path as on the host so the paths
# recorded in its .bundle/config remain valid. The gems are kept in a volume
# instead of the .gem directory of the site, since they are built for the
# OS of the container.
DOCKER_ARGS+=(
  -v "$SITE_DIR":"$SITE_DIR"
  -v "kudu-site-gems-$ARCH":"$SITE_DIR/.gem"
  -w "$SITE_DIR")

# If the site is a git checkout, e.g. a worktree, make its repository
# available as well, so that 'site_tool publish' works.
if [ -e "$SITE_DIR/.git" ]; then
  GIT_COMMON_DIR=$(git -C "$SITE_DIR" rev-parse --path-format=absolute \
    --git-common-dir)
  case "$GIT_COMMON_DIR" in
    "$SITE_DIR"/*) ;;
    *) DOCKER_ARGS+=(-v "$GIT_COMMON_DIR":"$GIT_COMMON_DIR") ;;
  esac
  GIT_NAME=$(git -C "$SITE_DIR" config user.name || :)
  GIT_EMAIL=$(git -C "$SITE_DIR" config user.email || :)
  DOCKER_ARGS+=(
    -e GIT_AUTHOR_NAME="$GIT_NAME" -e GIT_COMMITTER_NAME="$GIT_NAME"
    -e GIT_AUTHOR_EMAIL="$GIT_EMAIL" -e GIT_COMMITTER_EMAIL="$GIT_EMAIL")
fi

SITE_TOOL_ARGS=("$@")
if [ "$1" == "jekyll" ] && [ "$2" == "serve" ]; then
  SITE_PORT=${SITE_PORT:-4000}
  DOCKER_ARGS+=(-p "127.0.0.1:$SITE_PORT:4000")
  # Listen on all the interfaces of the container so the published port
  # is reachable from the host.
  SITE_TOOL_ARGS+=(--host 0.0.0.0 --port 4000)
  echo "Serving the site at http://localhost:$SITE_PORT/"
fi

docker run "${DOCKER_ARGS[@]}" "$IMAGE" bash -c '
  set -e
  # Docker creates the mount point of a new volume owned by root.
  sudo chown "$(id -u):$(id -g)" .gem
  git config --global --add safe.directory "*"
  # site_tool installs the latest bundler if it is not present, which may not
  # be compatible with the Ruby version in the image.
  if [ ! -x .gem/bin/bundle ]; then
    gem install --no-document -q --install-dir .gem bundler -v '"$BUNDLER_VERSION"'
  fi
  exec ./site_tool "$@"' site_tool "${SITE_TOOL_ARGS[@]}"
