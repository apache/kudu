# This script runs inside the container built from
# docs/support/docker/Dockerfile and is invoked by
# docs/support/scripts/make_site_docker.sh. It does the following:
#   1. Checks out $KUDU_SHA from the read-only source repository mounted at
#      $SRC_REPO into a workspace in the persistent /work volume. Thirdparty
#      and build artifacts are kept there between runs.
#   2. Runs make_site.sh in that workspace, passing all the arguments.
#   3. Copies the resulting site (without .git) into $KUDU_SITE_OUT, which is
#      mounted at the same path as on the host.
########################################################################
set -e
set -o pipefail

SRC_REPO=${SRC_REPO:-/src}
WORKSPACE=${WORKSPACE:-/work/kudu}
KUDU_SITE_REMOTE=${KUDU_SITE_REMOTE:-https://github.com/apache/kudu.git}

if [ -z "$KUDU_SHA" ] || [ -z "$KUDU_SITE_OUT" ]; then
  echo "Error: KUDU_SHA and KUDU_SITE_OUT must be set"
  exit 1
fi

# The source repository is owned by a different user on the host.
git config --global --add safe.directory '*'

if [ ! -d "$WORKSPACE/.git" ]; then
  git init -q "$WORKSPACE"
fi
cd "$WORKSPACE"

echo "Checking out $KUDU_SHA into $WORKSPACE"
git fetch -q "$SRC_REPO" "$KUDU_SHA"
# Don't run 'git clean' here: it would wipe out the thirdparty and build
# artifacts that are reused between runs.
git checkout -q --force --detach "$KUDU_SHA"

# make_site.sh clones the gh-pages branch from the 'origin' remote.
if git remote | grep -qx origin; then
  git remote set-url origin "$KUDU_SITE_REMOTE"
else
  git remote add origin "$KUDU_SITE_REMOTE"
fi

SITE_DIR="$WORKSPACE/build/release/site"
GEM_PATH="$WORKSPACE/build/release/gems"

# make_docs.sh installs the latest bundler if it's not present, which may not
# be compatible with the Ruby version in the image. Install the version the
# lockfile was generated with instead.
if [ ! -x "$GEM_PATH/bin/bundle" ]; then
  BUNDLER_VERSION=$(awk '/^BUNDLED WITH/ { getline; print $1 }' \
    docs/support/scripts/Gemfile.lock)
  gem install --no-document -q --install-dir "$GEM_PATH" \
    bundler -v "$BUNDLER_VERSION"
fi

TMP_DIR=$(mktemp -d)
trap "rm -rf $TMP_DIR" EXIT

# make_site.sh builds the binaries and the 'doxygen' target in a single ninja
# invocation. The 'doxygen' target runs a nested 'ninja install' that races
# with the outer ninja relinking the binaries. To avoid that, put a shim on
# the PATH which builds the 'doxygen' target in a separate invocation.
mkdir -p "$TMP_DIR/bin"
cat > "$TMP_DIR/bin/ninja" <<'EOF'
#!/bin/bash
set -e
ARGS=()
DOXYGEN=
for arg in "$@"; do
  if [ "$arg" == "doxygen" ]; then
    DOXYGEN=1
  else
    ARGS+=("$arg")
  fi
done
if [ ${#ARGS[@]} -gt 0 ] || [ -z "$DOXYGEN" ]; then
  /usr/bin/ninja "${ARGS[@]}"
fi
if [ -n "$DOXYGEN" ]; then
  /usr/bin/ninja doxygen
fi
EOF
chmod +x "$TMP_DIR/bin/ninja"

# --force is required since the site directory from the previous run is
# still present in the workspace.
PATH="$TMP_DIR/bin:$PATH" ./docs/support/scripts/make_site.sh --force "$@"

echo "Copying the generated site into $KUDU_SITE_OUT"
mkdir -p "$KUDU_SITE_OUT"
# Exclude the files generated by Jekyll and site_tool_docker.sh, which may be
# present if the output directory was previewed.
rsync -a --delete \
  --exclude /.git \
  --exclude /.gem \
  --exclude /.bundle \
  --exclude /_site \
  --exclude /.jekyll-cache \
  --exclude /.jekyll-metadata \
  "$SITE_DIR/" "$KUDU_SITE_OUT/"
